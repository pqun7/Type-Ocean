import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";
import Footer from "@/components/layout/Footer";
import Background from "@/components/ui/Background";
import { LevelProvider } from "@/features/level/context/LevelProvider";
import { AlertProvider } from "@/contexts/alert-context";
import { AlertState } from "@/components/ui/alert-state";
import { HandleAuthSuccess } from "@/components/handle-auth-success";
import { auth } from "@/features/auth/lib/auth";

const inter = Inter({
  subsets: ["latin"],
  display: "swap",
  preload: true,
  fallback: ["system-ui", "arial"],
  adjustFontFallback: false, // Disable to prevent Turbopack issues
});

export const metadata: Metadata = {
  title: "Type Ocean",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const session = await auth();
  const initialUserId = session?.user?.id ?? null;

  return (
    <html lang="en">
      <body
        className={`${inter.className} antialiased bg-n-11 font-sans text-n-1 text-base`}
        suppressHydrationWarning={true}
      >
        <Background className="fixed inset-0 pointer-events-none z-0" />

        <div className="relative z-10 min-h-screen flex flex-col">
          <LevelProvider initialUserId={initialUserId}>
            <AlertProvider>
              <AlertState />
              <HandleAuthSuccess />
              <main className="flex-grow">{children}</main>
              <Footer />
            </AlertProvider>
          </LevelProvider>
        </div>
      </body>
    </html>
  );
}
